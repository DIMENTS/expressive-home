test.each(OTHER)('the code of %s is the one another maker makes', (text, rows) => {
  expect(readQr(rows)).toBe(text);
  expect(qrWithMask(text, maskOf(rows))).toEqual(rows);
});

test.each([
  ['http://192.168.1.20:8790/#pair=482913', 29], ['http://192.168.100.200:8790/#pair=000000', 29], ['http://10.0.0.2:8790/#pair=123456', 29], ['', 21], ['a', 21], ['é€😀', 21],
  ['x'.repeat(14), 21], ['x'.repeat(15), 25], ['x'.repeat(26), 25], ['x'.repeat(27), 29], ['x'.repeat(42), 29], ['x'.repeat(43), 33], ['x'.repeat(62), 33], ['x'.repeat(63), 37], ['x'.repeat(84), 37], ['x'.repeat(85), 41], ['x'.repeat(106), 41],
])('%s reads back', (text, size) => {
  const rows = qrCode(text);
  expect(rows).toHaveLength(size);
  expect(readQr(rows)).toBe(text);
});

test('every mask reads back, and the one that is chosen is one of them', () => {
  const text = 'http://192.168.1.20:8790/#pair=482913';
  const all = Array.from({ length: 8 }, (_, mask) => qrWithMask(text, mask));
  expect(all.map(readQr)).toEqual(Array(8).fill(text));
  expect(all.map(maskOf)).toEqual([0, 1, 2, 3, 4, 5, 6, 7]);
  expect(new Set(all.map((rows) => rows.join(''))).size).toBe(8);
  expect(all).toContainEqual(qrCode(text));
});

test('what does not fit is refused', () => {
  expect(() => qrCode('x'.repeat(107))).toThrow(RangeError);
  expect(() => qrCode('€'.repeat(36))).toThrow(RangeError);
});

test('the reader notices what is wrong', () => {
  const rows = qrCode('http://192.168.1.20:8790/#pair=482913');
  const flipped = (y: number, x: number): string[] => rows.map((row, at) => (at === y ? `${row.slice(0, x)}${row[x] === '1' ? '0' : '1'}${row.slice(x + 1)}` : row));
  for (const [y, x] of [[0, 0], [6, 10], [8, 2], [20, 20], [18, 18], [28, 28]] as const) expect(() => readQr(flipped(y, x))).toThrow();
});
